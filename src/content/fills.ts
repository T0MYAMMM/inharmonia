// Shorthand: a note relative to the chord after the change, the chord before it, or the key.
const to = (o: Omit<FillPitch, 'ref'> = {}): FillPitch => ({ ref: 'to', ...o });
const from = (o: Omit<FillPitch, 'ref'> = {}): FillPitch => ({ ref: 'from', ...o });
const key = (o: Omit<FillPitch, 'ref'> = {}): FillPitch => ({ ref: 'key', ...o });
const hit = (at: number, dur: number, ...notes: FillPitch[]): FillHitSpec => ({ at, dur, notes });
const soft = (h: FillHitSpec): FillHitSpec => ({ ...h, velocity: 0.28 });
/** A diatonic sixth: the top voice `k` steps from the target root, the bottom a sixth below. */
const sixth = (at: number, dur: number, k: number): FillHitSpec =>
  hit(at, dur, to({ step: k, octave: 1 }), to({ step: k - 5, octave: 1 }));

